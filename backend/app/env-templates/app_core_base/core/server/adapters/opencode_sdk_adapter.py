@AdapterRegistry.register
class OpenCodeAdapter(BaseSDKAdapter):
    """
    OpenCode adapter — wraps an `opencode serve` HTTP server.

    Each mode (building / conversation) gets its own adapter instance with
    its own opencode serve process on a dedicated port, so there is no
    shared state between concurrent building and conversation sessions.

    Supports all opencode/* variants. Provider is determined from the
    config files generated at environment creation time.
    """

    ADAPTER_TYPE = "opencode"
    SUPPORTED_PROVIDERS = [
        "anthropic", "openai", "openai_compatible",
        "google", "default",
    ]

    def __init__(self, config: SDKConfig):
        super().__init__(config)

        self.prompt_generator = PromptGenerator(self.workspace_dir)

        # Agent env service for plugin management (mirrors ClaudeCodeAdapter)
        self.agent_env_service = AgentEnvService(self.workspace_dir)

        # Server process — started lazily on first send_message_stream call
        self._server_process: Optional[asyncio.subprocess.Process] = None

        # Lock to prevent concurrent server starts
        self._start_lock = asyncio.Lock()

        # Current session ID — tracked across calls
        self._current_session_id: Optional[str] = None

        # Per-mode port and runtime dir are resolved on first use
        # (when mode is known from send_message_stream)
        self._mode: Optional[str] = None
        self._port: Optional[int] = None
        self._base_url: Optional[str] = None
        self._runtime_dir: Optional[Path] = None

        # Plugin capabilities OpenCode can't map (skills/agents/hooks), collected
        # at server start for non-blocking reporting at session start. List of
        # {plugin_name, marketplace_name, capability, message}.
        self._plugin_unsupported: list[dict] = []

        # Event transformer — translates raw OpenCode SSE events to SDKEvents
        self._event_transformer = OpenCodeEventTransformer(self.workspace_dir)

        # Strong references to fire-and-forget background tasks (e.g. the
        # /question/{id}/reject call fired on the interrupt/teardown path).
        # Prevents Python GC from collecting the task reference mid-flight and
        # raising "Task was destroyed but it is pending!" warnings.
        self._background_tasks: set[asyncio.Task] = set()

        # Pending interactive `question` tools, keyed by opencode session id.
        # Populated when a `question.asked` requestID is captured during a
        # stream; the NEXT message for that session is treated as the answer
        # and relayed via POST /question/{id}/reply instead of a fresh message
        # post.  This is the in-memory fast path; GET /question is the
        # authoritative, parameter-free source of truth (see
        # _resolve_pending_question).  Each value is
        # ``{"id": request_id, "questions": [...]}``.
        self._pending_questions: dict[str, dict] = {}

    def _resolve_mode(self, mode: str) -> None:
        """
        Resolve per-mode paths and port on first use.

        Called once per adapter instance — subsequent calls with the same
        mode are no-ops.  Different modes get different adapter instances
        via SDKManager caching.
        """
        if self._mode == mode:
            return
        self._mode = mode
        self._port = OPENCODE_MODE_PORTS.get(mode, 4096)
        self._base_url = f"http://127.0.0.1:{self._port}"
        self._runtime_dir = Path(OPENCODE_RUNTIME_DIR_TEMPLATE.format(mode=mode))

    # ------------------------------------------------------------------
    # Process management
    # ------------------------------------------------------------------

    async def _start_opencode_server(self) -> None:
        """
        Launch `opencode serve` as an asyncio subprocess.

        Each mode gets its own server process on a dedicated port with its
        own runtime directory.  Config files are symlinked from the read-only
        per-mode config dir (/app/core/.opencode/{mode}/) into the writable
        runtime dir (/tmp/.opencode_{mode}/).
        """
        logger.info(
            "Starting opencode serve for mode=%s on port %d...",
            self._mode, self._port,
        )

        # Ensure the runtime directory exists (writable, unlike OPENCODE_CONFIG_DIR
        # which is mounted read-only via the /app/core:ro volume).
        self._runtime_dir.mkdir(parents=True, exist_ok=True)

        # Symlink static config files from the read-only per-mode config dir
        # into the writable runtime dir so opencode finds everything in one place.
        # opencode.json is the exception: it is MATERIALIZED (a real merged file,
        # not a symlink) so we can fold in the active plugins' MCP servers, which
        # change dynamically (Phase 1 install) without a rebuild.
        mode_config_dir = OPENCODE_CONFIG_DIR / self._mode
        if mode_config_dir.is_dir():
            for config_file in mode_config_dir.iterdir():
                if not config_file.is_file():
                    continue
                if config_file.name == "opencode.json":
                    continue  # handled by _materialize_opencode_config below
                link = self._runtime_dir / config_file.name
                if not link.exists():
                    link.symlink_to(config_file)

        # Materialize opencode.json with plugin MCP servers merged in + copy
        # plugin command files into the runtime command dir. Plugin capabilities
        # OpenCode can't map are collected here for non-blocking reporting at
        # session start.
        self._plugin_unsupported = self._materialize_opencode_config(mode_config_dir)

        # Sessions are bound to /app/workspace as their project directory (via
        # the `directory` query param) so file tools operate in the workspace.
        # Consequences that this env handles:
        #   * opencode loads project config by walking up from the project dir
        #     (/app/workspace), NOT from cwd — so it would no longer find our
        #     per-mode opencode.json. OPENCODE_CONFIG pins it explicitly.
        #   * opencode spawns local MCP servers (the knowledge / agent_task
        #     bridges) with cwd = the project dir (/app/workspace), so they can
        #     no longer read session_context.json from cwd. We pass its absolute
        #     path so the bridges resolve it regardless of their cwd.
        # The system prompt is delivered via the config's `instructions` entry
        # (absolute AGENTS.md path), so cwd-based AGENTS.md discovery is not
        # needed either.
        env = {
            **os.environ,
            "OPENCODE_SKIP_UPDATE": "1",
            "OPENCODE_CONFIG": str(self._runtime_dir / "opencode.json"),
            "CINNA_SESSION_CONTEXT_PATH": str(self._runtime_dir / "session_context.json"),
        }

        # cwd stays at the runtime dir (where the adapter writes opencode.json,
        # AGENTS.md, and session_context.json); the workspace project binding is
        # applied per request via the `directory` query param.
        self._server_process = await asyncio.create_subprocess_exec(
            "opencode", "serve",
            "--port", str(self._port),
            "--hostname", "127.0.0.1",
            stdout=asyncio.subprocess.DEVNULL,
            stderr=asyncio.subprocess.DEVNULL,
            env=env,
            cwd=str(self._runtime_dir),
        )

        logger.info(
            "opencode serve started for mode=%s (pid=%d, port=%d)",
            self._mode, self._server_process.pid, self._port,
        )

        # Wait for the server to become healthy
        await self._wait_for_server_health()

    async def _wait_for_server_health(self) -> None:
        """Poll the server until it responds or the timeout is reached."""
        aiohttp = _import_aiohttp()
        if aiohttp is None:
            # Can't check health without aiohttp — give a fixed delay
            await asyncio.sleep(3)
            return

        deadline = asyncio.get_running_loop().time() + OPENCODE_STARTUP_TIMEOUT
        last_error: Optional[Exception] = None

        while asyncio.get_running_loop().time() < deadline:
            # Check if process died already
            if self._server_process and self._server_process.returncode is not None:
                raise RuntimeError(
                    f"opencode serve exited prematurely with code "
                    f"{self._server_process.returncode}"
                )

            try:
                async with aiohttp.ClientSession() as session:
                    # Try /health first; fall back to /doc (always exists)
                    for path in ("/health", "/doc"):
                        try:
                            async with session.get(
                                f"{self._base_url}{path}",
                                timeout=aiohttp.ClientTimeout(total=2),
                            ) as resp:
                                if resp.status < 500:
                                    logger.info(
                                        "opencode serve is healthy (status=%d on %s)",
                                        resp.status, path,
                                    )
                                    return
                        except Exception:
                            pass
            except Exception as exc:
                last_error = exc

            await asyncio.sleep(1)

        raise RuntimeError(
            f"opencode serve did not become healthy within "
            f"{OPENCODE_STARTUP_TIMEOUT}s. Last error: {last_error}"
        )

    async def _ensure_server_running(self) -> None:
        """
        Ensure the opencode server is running. Starts it if not running.

        Uses a lock to prevent multiple concurrent starts.
        """
        async with self._start_lock:
            # Check if process exists and is still alive
            process_alive = (
                self._server_process is not None
                and self._server_process.returncode is None
            )

            if not process_alive:
                if self._server_process is not None:
                    logger.warning(
                        "opencode serve process exited (code=%d), restarting...",
                        self._server_process.returncode,
                    )
                # Clear stale session ID so the next request creates a fresh session
                self._current_session_id = None
                await self._start_opencode_server()

    # ------------------------------------------------------------------
    # HTTP helpers
    # ------------------------------------------------------------------

    async def _create_session(self) -> str:
        """
        POST /session — create a new OpenCode session.

        Returns the session ID string.
        """
        aiohttp = _import_aiohttp()
        if aiohttp is None:
            raise RuntimeError("aiohttp is required for OpenCodeAdapter but is not installed")

        async with aiohttp.ClientSession() as session:
            async with session.post(
                f"{self._base_url}/session",
                # Bind the session to the agent workspace as its project root.
                # Without this, opencode uses the server's cwd (the runtime
                # config dir under /tmp) as the project, so file tools
                # (write/edit/apply_patch/bash) resolve relative paths to /tmp
                # instead of /app/workspace — making created files invisible to
                # the workspace, the /files browser, and message attachments.
                params={"directory": self.workspace_dir},
                json={},
                timeout=aiohttp.ClientTimeout(total=30),
            ) as resp:
                resp.raise_for_status()
                data = await resp.json()
                session_id = data.get("id") or data.get("sessionId") or data.get("session_id")
                if not session_id:
                    raise RuntimeError(f"POST /session returned no session id: {data}")
                logger.info("Created OpenCode session: %s", session_id)
                self._event_transformer.event_logger.log_send(
                    "create_session", {"session_id": session_id}
                )
                return session_id

    async def _post_message(self, session_id: str, message: str) -> None:
        """
        POST /session/:id/message — send a user message to the session.

        This triggers OpenCode to start processing; actual response comes
        through the SSE stream on GET /global/event.
        """
        aiohttp = _import_aiohttp()
        if aiohttp is None:
            raise RuntimeError("aiohttp is required for OpenCodeAdapter but is not installed")

        body = {
            "role": "user",
            "parts": [{"type": "text", "text": message}],
        }

        async with aiohttp.ClientSession() as session:
            async with session.post(
                f"{self._base_url}/session/{session_id}/message",
                # Keep the request scoped to the workspace project so message
                # processing and tool execution run in /app/workspace (matches
                # the directory the session was created with).
                params={"directory": self.workspace_dir},
                json=body,
                timeout=aiohttp.ClientTimeout(total=60),
            ) as resp:
                if resp.status >= 400:
                    text = await resp.text()
                    raise RuntimeError(
                        f"POST /session/{session_id}/message failed "
                        f"({resp.status}): {text}"
                    )
                logger.info("Message sent to OpenCode session %s", session_id)
                self._event_transformer.event_logger.log_send(
                    "post_message",
                    {"session_id": session_id, "message": message},
                )

    # ------------------------------------------------------------------
    # System prompt
    # ------------------------------------------------------------------

    async def _write_agents_md(self, system_prompt: str) -> None:
        """Write the system prompt to AGENTS.md in the runtime directory."""
        agents_md_path = self._runtime_dir / OPENCODE_AGENTS_MD_FILENAME
        self._runtime_dir.mkdir(parents=True, exist_ok=True)
        agents_md_path.write_text(system_prompt, encoding="utf-8")
        logger.info("Wrote AGENTS.md (%d chars)", len(system_prompt))
        self._event_transformer.event_logger.log_send(
            "write_agents_md", {"chars": len(system_prompt)}
        )

    async def _write_session_context(
        self,
        opencode_session_id: str,
        backend_session_id: Optional[str],
    ) -> None:
        """
        Write session context for MCP bridge servers.

        The MCP bridge servers (knowledge_server.py, task_server.py)
        read this file at tool-call time to obtain the
        current backend_session_id without needing to be passed it at startup.
        """
        context = {
            "opencode_session_id": opencode_session_id,
            "backend_session_id": backend_session_id or "",
        }
        context_path = self._runtime_dir / "session_context.json"
        self._runtime_dir.mkdir(parents=True, exist_ok=True)
        context_path.write_text(json.dumps(context, indent=2), encoding="utf-8")
        logger.debug(
            "Wrote session_context.json (opencode=%s, backend=%s)",
            opencode_session_id,
            backend_session_id,
        )

    def _materialize_opencode_config(self, mode_config_dir: Path) -> list[dict]:
        """Write a runtime opencode.json with active plugins' MCP servers merged in.

        The base config is the read-only per-mode ``opencode.json`` (model,
        provider, permissions, the knowledge/agent_task MCP bridges). We fold in
        each active plugin's *declared* MCP servers (from its ``.mcp.json`` /
        ``plugin.json`` — NOT a python3 wrapper of the plugin dir) and copy the
        plugin's ``commands/*.md`` into the runtime command dir so OpenCode loads
        them as slash commands.

        Returns the list of unsupported-capability reports (skills/agents/hooks)
        for non-blocking surfacing at session start.

        Writes are confined to the per-mode runtime dir (opencode.json + the
        ``command/`` subdir); plugin files are only read.
        """
        base_config_path = mode_config_dir / "opencode.json"
        try:
            if base_config_path.is_file():
                config = json.loads(base_config_path.read_text(encoding="utf-8"))
            else:
                logger.warning("No base opencode.json at %s", base_config_path)
                config = {}
        except (OSError, json.JSONDecodeError) as e:
            logger.error("Failed to read base opencode.json: %s", e)
            config = {}

        unsupported: list[dict] = []
        try:
            artifacts = self.agent_env_service.get_opencode_plugin_artifacts(self._mode)
        except Exception as e:  # noqa: BLE001
            logger.warning("Could not build plugin artifacts: %s", e)
            artifacts = {"mcp_servers": {}, "command_files": [], "unsupported": []}

        # 1) Merge plugin MCP servers into the config's mcp section. Plugin keys
        #    are namespaced (plugin_<mkt>_<plugin>_<server>) so they never clobber
        #    the knowledge / agent_task bridges.
        plugin_mcp = artifacts.get("mcp_servers") or {}
        if plugin_mcp:
            mcp_section = config.get("mcp")
            if not isinstance(mcp_section, dict):
                mcp_section = {}
            mcp_section.update(plugin_mcp)
            config["mcp"] = mcp_section

        # 1b) Merge credential-derived MCP-provider servers (RD-5). These are
        #     namespaced cinna_mcp_<credential_id> so they never collide with the
        #     knowledge / agent_task bridges or plugin_* servers.
        try:
            user_mcp = self.agent_env_service.get_user_mcp_servers_for_mode(
                self._mode, engine="opencode"
            )
        except Exception as e:  # noqa: BLE001
            logger.warning("Could not build user MCP servers: %s", e)
            user_mcp = {}
        if user_mcp:
            mcp_section = config.get("mcp")
            if not isinstance(mcp_section, dict):
                mcp_section = {}
            mcp_section.update(user_mcp)
            config["mcp"] = mcp_section
            logger.info(
                "OpenCode %s: merged %d MCP-provider server(s)",
                self._mode, len(user_mcp),
            )

        # 2) Copy plugin command markdown into the runtime command dir.
        self._copy_plugin_commands(artifacts.get("command_files") or [])

        # 3) Collect unsupported capabilities for reporting.
        unsupported = artifacts.get("unsupported") or []

        # Write the merged config into the runtime dir (real file, replaces any
        # stale symlink/file from a prior start).
        runtime_config = self._runtime_dir / "opencode.json"
        try:
            if runtime_config.is_symlink() or runtime_config.exists():
                runtime_config.unlink()
            runtime_config.write_text(json.dumps(config, indent=2), encoding="utf-8")
            try:
                os.chmod(runtime_config, 0o600)
            except OSError:
                pass
        except OSError as e:
            logger.error("Failed to write runtime opencode.json: %s", e)

        if plugin_mcp or unsupported:
            logger.info(
                "OpenCode %s plugins: %d MCP server(s), %d command file(s), "
                "%d unsupported capability report(s)",
                self._mode, len(plugin_mcp),
                len(artifacts.get("command_files") or []), len(unsupported),
            )
        return unsupported

    def _active_plugin_mcp_keys(self) -> list[str]:
        """Return plugin MCP server keys merged into the runtime opencode.json.

        Reads the materialized config so the advertised tool names exactly match
        what OpenCode actually loaded. Plugin servers are keyed ``plugin_*`` to
        distinguish them from the knowledge / agent_task bridges.
        """
        if not self._runtime_dir:
            return []
        runtime_config = self._runtime_dir / "opencode.json"
        try:
            data = json.loads(runtime_config.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            return []
        mcp = data.get("mcp")
        if not isinstance(mcp, dict):
            return []
        return [k for k in mcp if isinstance(k, str) and k.startswith("plugin_")]

    def _copy_plugin_commands(self, command_files: list) -> None:
        """Reconcile plugin command ``*.md`` files in the runtime ``command/`` dir.

        OpenCode loads slash commands from ``<config_dir>/command/``. This dir is
        entirely plugin-managed for the runtime, so it is CLEARED first (removing
        commands left over from a prior server generation — e.g. a plugin that was
        uninstalled then the server restarted within the same container) and then
        repopulated from the current active plugins. Writes are confined to the
        runtime command dir; a name collision keeps the first file and skips later
        ones (logged) so two plugins can't silently shadow each other.
        """
        command_dir = self._runtime_dir / "command"

        # Clear any stale plugin commands from a previous generation. Confined to
        # the runtime command dir; only *.md files are removed (defensive).
        if command_dir.exists():
            try:
                for stale in command_dir.glob("*.md"):
                    if stale.is_file():
                        stale.unlink()
            except OSError as e:
                logger.warning("Failed to clear stale command dir: %s", e)

        if not command_files:
            return

        try:
            command_dir.mkdir(parents=True, exist_ok=True)
        except OSError as e:
            logger.error("Failed to create command dir %s: %s", command_dir, e)
            return

        seen: set[str] = set()
        for src in command_files:
            try:
                src_path = Path(src)
                name = src_path.name
                if name in seen:
                    logger.warning(
                        "Skipping duplicate plugin command file: %s", name
                    )
                    continue
                dest = command_dir / name
                # Defence: confirm dest stays within the command dir.
                if dest.resolve().parent != command_dir.resolve():
                    logger.warning("Rejected unsafe command file name: %s", name)
                    continue
                shutil.copy2(src_path, dest)
                seen.add(name)
            except OSError as e:
                logger.warning("Failed to copy plugin command %s: %s", src, e)

    # ------------------------------------------------------------------
    # SSE event parsing
    # ------------------------------------------------------------------

    @staticmethod
    def _parse_sse_event(raw_data: str) -> Optional[dict]:
        """
        Parse a single SSE data payload into a dict.

        OpenCode wraps events in a ``{"payload": {...}}`` envelope.
        This method unwraps it so callers always see the inner event dict
        with ``type`` and ``properties`` at the top level.

        Returns None if parsing fails or the payload is not meaningful.
        """
        stripped = raw_data.strip()
        if not stripped or stripped == ":":
            return None
        try:
            parsed = json.loads(stripped)
            # Unwrap the payload envelope if present
            if "payload" in parsed and isinstance(parsed["payload"], dict):
                parsed = parsed["payload"]
            return parsed
        except json.JSONDecodeError:
            logger.debug("Skipping non-JSON SSE data: %s", stripped[:100])
            return None

    @staticmethod
    def _event_session_id(event_data: dict) -> Optional[str]:
        """
        Extract the opencode session ID an event belongs to, if any.

        ``GET /global/event`` is a serve-wide stream shared by every session on
        the mode's serve process, so each event must be matched against the
        session we are actually streaming for. Different event shapes nest the
        session ID differently:

            properties.sessionID          — most message / session events
            properties.part.sessionID     — message.part.updated / .delta
            properties.info.sessionID     — some session.* snapshots

        Server lifecycle events (server.connected, server.heartbeat,
        project.updated, …) carry NO session ID — those return None and must be
        treated as session-agnostic by the caller (they still drive the
        "first event triggers the POST" handshake in the SSE loop).
        """
        properties = event_data.get("properties")
        if not isinstance(properties, dict):
            return None

        sid = properties.get("sessionID")
        if sid:
            return sid

        part = properties.get("part")
        if isinstance(part, dict):
            sid = part.get("sessionID")
            if sid:
                return sid

        info = properties.get("info")
        if isinstance(info, dict):
            sid = info.get("sessionID")
            if sid:
                return sid

        return None

