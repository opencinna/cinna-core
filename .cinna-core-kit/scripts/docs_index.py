#!/usr/bin/env python3
"""
Docs index — one source of truth (frontmatter in each feature's primary doc),
two views: a generated Feature Registry block in docs/README.md for humans, and
compact / searchable / graph views for LLM agents.

Usage:
    python3 .cinna-core-kit/scripts/docs_index.py <command> [options]

Commands:
    registry [--check]        Regenerate the Feature Registry block in docs/README.md
                              (--check: exit 1 if the block is stale, write nothing)
    summary [--domain D]      Compact feature list: name — one_liner (per domain)
    search TERM [--limit N] [--feature F] [--domain D] [--include-plans]
                              Case-insensitive text search across docs; hits are
                              grouped by file with feature + nearest heading
    impact [--files F...] [--base REF] [--include-plans]
                              Docs that cover the changed files (default: working
                              tree vs HEAD, plus untracked), expanded one hop along
                              `affects` edges
    path FROM TO              Shortest chain between two features over the doc graph
    graph [--feature F]       Dump feature edges (derived links + authored affects)
    stale [--feature F]       Docs whose referenced code has commits newer than the
                              doc's own last commit (advisory)
    check [--verbose]         Registry block up to date, frontmatter valid, one_liner
                              cap, orphan code modules, route citations vs OpenAPI,
                              tech-doc anchoring. Exit 1 on failures.
    seed                      ONE-TIME migration: derive frontmatter skeletons from
                              the hand-written registry rows and wrap the block in
                              markers. Skips docs that already carry frontmatter.

Frontmatter (first thing in the feature's primary doc):

    ---
    feature: server_channels
    domain: application              # or a list: [application, knowledge]
    one_liner: "Admin-configured server-wide inbound channels routing outside senders to agents."
    docs:                            # other docs of the feature, label -> path
      tech: server_channels_tech.md  # relative to this doc's dir, or docs/-rooted
      debug monitor tech: channel_debug_monitor_tech.md
    primary_label: business logic    # optional; label of THIS doc in the registry
    affects: [routing_tuning]        # optional, directional: change here => review there
    covers: [backend/app/services/server_channels/**]   # optional override globs
    ---

`related` is never authored — it is derived from the links the docs already carry.
"""

