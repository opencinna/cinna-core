def indexed_docs(include_plans=False):
    """All docs under docs/ that the index reasons about (plans excluded by default)."""
    out = []
    for dirpath, dirnames, files in os.walk(DOCS):
        r = rel(dirpath)
        if not include_plans and r.startswith("docs/plans"):
            dirnames[:] = []
            continue
        for f in files:
            if f.endswith(".md"):
                out.append(rel(os.path.join(dirpath, f)))
    return sorted(out)


