def cmd_summary(args):
    only = _opt(args, "--domain")
    idx = Index()
    by_domain = defaultdict(list)
    for f in idx.features.values():
        for d in f.domains:
            by_domain[d].append(f)
    for d in idx.domain_order() + sorted(set(by_domain) - set(idx.domain_order())):
        if only and d != only:
            continue
        feats = sorted(by_domain.get(d, []), key=lambda f: f.name)
        if not feats:
            continue
        print("## %s" % d)
        for f in feats:
            extra = ", ".join("%s: %s" % (l, p) for l, p in f.docs[1:])
            print("- %s — %s  <%s>%s" % (f.name, f.one_liner, f.primary, ("  [%s]" % extra) if extra else ""))
        print()
    return 0


