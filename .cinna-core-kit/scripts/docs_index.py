def cmd_seed(args):
    """Derive frontmatter skeletons from the hand-written registry, once."""
    text = read("docs/README.md")
    if REGISTRY_START in text:
        print("README already carries registry markers; seed is a one-time migration.")
        return 1
    start = text.find("## Feature Registry")
    end = text.find("## Architecture Overview")
    if start < 0 or end < 0:
        print("could not locate the Feature Registry section")
        return 1
    section = text[start:end]
    domain = None
    seeded, merged, skipped = [], [], []
    for line in section.split("\n"):
        if line.startswith("### "):
            domain = line[4:].strip()
            continue
        if not re.match(r"^\| [a-z_]+ \|", line):
            continue
        cells = [c.strip() for c in CELL_SPLIT_RE.split(line.strip().strip("|"))]
        if len(cells) < 3:
            continue
        name, desc = cells[0], cells[1]
        docs_cell = next((c for c in reversed(cells) if LINK_RE.search(c)), "")
        links = [(l.strip(), p.strip()) for l, p in LINK_RE.findall(docs_cell)]
        if not links:
            skipped.append((name, "no doc links"))
            continue
        primary_label, primary_rel = links[0]
        primary = "docs/" + primary_rel
        if not os.path.exists(os.path.join(ROOT, primary)):
            skipped.append((name, "primary doc missing: " + primary))
            continue
        existing = read(primary)
        fm, body = parse_frontmatter(existing)
        if fm is not None:
            # Cross-listed row (e.g. `workspaces` under sharing pointing at user_workspaces docs):
            # add the domain to the existing feature instead of creating a duplicate.
            doms = fm["domain"] if isinstance(fm["domain"], list) else [fm["domain"]]
            if domain not in doms:
                doms.append(domain)
            fm["domain"] = doms
            with open(os.path.join(ROOT, primary), "w", encoding="utf-8") as fh:
                fh.write(dump_frontmatter(fm) + body)
            merged.append((name, fm["feature"], domain))
            continue
        base = os.path.dirname(primary)
        docs = {}
        for label, p in links[1:]:
            docs[label] = os.path.relpath("docs/" + p, base).replace(os.sep, "/")
        plain = re.sub(r"[*`_]", "", desc)
        first = re.split(r"(?<=[.;])\s", plain, 1)[0]
        one_liner = "TODO " + first[:ONE_LINER_MAX - 5].rstrip()
        fm = {
            "feature": name,
            "domain": domain,
            "one_liner": one_liner,
            "docs": docs,
            "primary_label": primary_label,
        }
        with open(os.path.join(ROOT, primary), "w", encoding="utf-8") as fh:
            fh.write(dump_frontmatter(fm) + existing)
        seeded.append((name, primary))
    # Wrap the registry section in markers; the old rows stay until `registry` regenerates.
    new_section = "## Feature Registry\n\n" + REGISTRY_START + "\n" + section[len("## Feature Registry"):].strip("\n") + "\n" + REGISTRY_END + "\n\n"
    with open(README, "w", encoding="utf-8") as fh:
        fh.write(text[:start] + new_section + text[end:])
    print("seeded %d features, merged %d cross-listed rows, skipped %d" % (len(seeded), len(merged), len(skipped)))
    for m in merged:
        print("  merged row `%s` into feature `%s` (domain %s)" % m)
    for s in skipped:
        print("  skipped `%s`: %s" % s)
    print("Next: replace every `TODO` one_liner, then run `registry` and `check`.")
    return 0


