def _glob_re(g):
    out = ""
    i = 0
    while i < len(g):
        if g.startswith("**/", i):
            out += "(?:.*/)?"
            i += 3
        elif g.startswith("**", i):
            out += ".*"
            i += 2
        elif g[i] == "*":
            out += "[^/]*"
            i += 1
        elif g[i] == "?":
            out += "."
            i += 1
        else:
            out += re.escape(g[i])
            i += 1
    return re.compile("^" + out + "$")


def changed_files(args):
    files = _opt_list(args, "--files")
    if files:
        return sorted(set(f.replace(os.sep, "/") for f in files))
    base = _opt(args, "--base")
    if base:
        out = _git(["diff", "--name-only", base])
    else:
        out = _git(["diff", "--name-only", "HEAD"]) + "\n" + _git(
            ["ls-files", "--others", "--exclude-standard"]
        )
    return sorted(set(l.strip() for l in out.split("\n") if l.strip()))


def covering_docs(idx, files):
    """{doc: [(file, how)]} for docs whose references or covers globs match the files."""
    result = defaultdict(list)
    cover_res = {}
    for f in idx.features.values():
        if f.covers:
            cover_res[f.name] = [_glob_re(g) for g in f.covers]
    for doc in idx.docs:
        refs = idx.refs.get(doc, set())
        owner = idx.owner.get(doc)
        for ch in files:
            if ch.startswith("docs/"):
                continue
            hit = None
            for r in refs:
                if r == ch:
                    hit = r
                    break
                # A directory reference counts only when it is specific enough:
                # `backend/app/services/server_channels/` yes, `backend/app/` no.
                if ch.startswith(r.rstrip("/") + "/") and len(r.rstrip("/").split("/")) >= MIN_DIR_REF_DEPTH:
                    hit = r
                    break
            if hit is None and owner in cover_res:
                for cre in cover_res[owner]:
                    if cre.match(ch):
                        hit = "covers:" + cre.pattern
                        break
            if hit is not None:
                result[doc].append((ch, hit))
    return result


def cmd_impact(args):
    idx = Index(include_plans="--include-plans" in args)
    files = changed_files(args)
    code = [f for f in files if not f.startswith("docs/")]
    if not code:
        print("no changed code files (docs-only change or clean tree)")
        return 0
    direct = covering_docs(idx, code)
    print("Changed code files: %d" % len(code))
    if not direct:
        print("No doc names any of the changed files. Consider: is a new feature undocumented?")
        for f in code:
            print("  ", f)
        return 0
    print("\nDocs that name changed files:")
    touched_features = set()
    for doc in sorted(direct):
        owner = idx.owner.get(doc)
        if owner:
            touched_features.add(owner)
        print("  %s  [%s]" % (doc, owner or "-"))
        for ch, how in direct[doc][:6]:
            print("      %s" % ch + ("" if how == ch else "   (via %s)" % how))
        if len(direct[doc]) > 6:
            print("      ... +%d more" % (len(direct[doc]) - 6))
    hop = []
    for name in sorted(touched_features):
        for a in idx.features[name].affects:
            if a in idx.features and a not in touched_features:
                hop.append((a, name))
    if hop:
        print("\nOne hop along `affects` (review these too):")
        for a, src in hop:
            print("  %s  <%s>   because %s affects it" % (a, idx.features[a].primary, src))
    changed_docs = [f for f in files if f.startswith("docs/")]
    if changed_docs:
        print("\nDocs already changed in this diff: %d" % len(changed_docs))
    return 0


# ---------------------------------------------------------------- graph / path


def cmd_graph(args):
    only = _opt(args, "--feature")
    idx = Index()
    names = [only] if only else sorted(idx.features)
    for n in names:
        if n not in idx.features:
            print("unknown feature:", n)
            return 1
        f = idx.features[n]
        print("%s  <%s>" % (n, f.primary))
        for g in sorted(idx.related.get(n, ())):
            print("   related  %s" % g)
        for g in f.affects:
            print("   affects  %s" % g)
        for g in sorted(idx.features):
            if n in idx.features[g].affects:
                print("   affected-by  %s" % g)
    return 0


def cmd_path(args):
    pos = [a for a in args if not a.startswith("--")]
    if len(pos) != 2:
        print("usage: path FROM TO")
        return 2
    src, dst = pos
    idx = Index()
    for n in (src, dst):
        if n not in idx.features:
            print("unknown feature:", n)
            return 1
    prev = {src: None}
    q = deque([src])
    while q:
        cur = q.popleft()
        if cur == dst:
            break
        for nb in sorted(idx.neighbours(cur)):
            if nb not in prev:
                prev[nb] = cur
                q.append(nb)
    if dst not in prev:
        print("no path between %s and %s" % (src, dst))
        return 1
    chain = []
    cur = dst
    while cur is not None:
        chain.append(cur)
        cur = prev[cur]
    chain.reverse()
    for i, n in enumerate(chain):
        print(("  " if i else "") + ("-> " if i else "") + "%s  <%s>" % (n, idx.features[n].primary))
    return 0


# -------------------------------------------------------------------- stale


def _last_commit_times(paths):
    """{path: unix time of last commit touching it}; one git call per path batch."""
    times = {}
    for i in range(0, len(paths), 200):
        batch = paths[i : i + 200]
        out = _git(["log", "--format=%ct", "--name-only", "--", *batch])
        ts = None
        for line in out.split("\n"):
            line = line.strip()
            if not line:
                continue
            if line.isdigit():
                ts = int(line)
                continue
            if line in batch and line not in times:
                times[line] = ts
    return times


def cmd_stale(args):
    only = _opt(args, "--feature")
    idx = Index()
    docs = [d for d in idx.docs if (not only or idx.owner.get(d) == only)]
    code_refs = set()
    for d in docs:
        code_refs.update(r for r in idx.refs.get(d, ()) if not r.startswith("docs/") and os.path.exists(os.path.join(ROOT, r)))
    times = _last_commit_times(docs + sorted(code_refs))
    rows = []
    for d in docs:
        dt = times.get(d)
        if dt is None:
            continue
        newer = [
            (times.get(r, 0), r)
            for r in idx.refs.get(d, ())
            if not r.startswith("docs/") and times.get(r, 0) > dt
        ]
        if newer:
            newer.sort(reverse=True)
            rows.append((len(newer), d, newer[0][1]))
    rows.sort(reverse=True)
    if not rows:
        print("no docs older than the code they reference")
        return 0
    print("Docs whose referenced code changed after the doc's last commit (advisory):")
    for n, d, newest in rows:
        print("  %3d newer  %s  [%s]  e.g. %s" % (n, d, idx.owner.get(d, "-"), newest))
    return 0


# -------------------------------------------------------------------- check


def _allowlist():
    pats = []
    if os.path.exists(ALLOWLIST):
        for line in open(ALLOWLIST, encoding="utf-8"):
            line = line.split("#", 1)[0].strip()
            if line:
                pats.append(line)
    return pats


def orphan_modules(idx):
    mods = []
    for base in ("backend/app/services", "backend/app/api/routes"):
        for dirpath, _, files in os.walk(os.path.join(ROOT, base)):
            for f in files:
                if f.endswith(".py") and f != "__init__.py":
                    mods.append(rel(os.path.join(dirpath, f)))
    corpus = "\n".join(idx.text[p] for p in idx.docs)
    allow = _allowlist()
    out = []
    for m in sorted(mods):
        if os.path.basename(m) in corpus:
            continue
        if any(fnmatch.fnmatch(m, a) for a in allow):
            continue
        out.append(m)
    return out


def stale_routes(idx):
    if not os.path.exists(OPENAPI):
        return None
    spec = json.load(open(OPENAPI, encoding="utf-8"))
    norm = lambda p: re.sub(r"\{[^}]+\}", "{}", p.split("?")[0].rstrip("/").rstrip("]."))
    known = {norm(p) for p in spec.get("paths", {})}
    out = []
    for p in idx.docs:
        for n, line in enumerate(strip_frontmatter(idx.text[p]).split("\n"), 1):
            if "<!-- nocheck -->" in line:
                continue
            for m in ROUTE_RE.finditer(line):
                if norm(m.group(2)) not in known:
                    out.append((p, n, m.group(1) + " " + m.group(2)))
    return out


def cmd_check(args):
    verbose = "--verbose" in args
    idx = Index()
    failures = 0

    def section(title, items, failing=True, fmt=lambda x: x):
        nonlocal failures
        if not items:
            print("OK   %s" % title)
            return
        print("%s %s (%d)" % ("FAIL" if failing else "WARN", title, len(items)))
        for it in items if (verbose or len(items) <= 25) else items[:25]:
            print("     " + fmt(it))
        if not verbose and len(items) > 25:
            print("     ... +%d more (--verbose)" % (len(items) - 25))
        if failing:
            failures += 1

    section("frontmatter parses without conflicts", idx.errors)

    fm_errors = []
    order = set(idx.domain_order())
    for f in idx.features.values():
        if not f.one_liner or f.one_liner.startswith("TODO"):
            fm_errors.append("%s: one_liner missing or TODO" % f.primary)
        elif len(f.one_liner) > ONE_LINER_MAX:
            fm_errors.append("%s: one_liner is %d chars (max %d)" % (f.primary, len(f.one_liner), ONE_LINER_MAX))
        for d in f.domains:
            if d not in order:
                fm_errors.append("%s: domain `%s` is not in the README Domain Map" % (f.primary, d))
        for label, p in f.docs:
            if not os.path.exists(os.path.join(ROOT, p)):
                fm_errors.append("%s: docs.%s -> %s does not exist" % (f.primary, label, p))
        for a in f.affects:
            if a not in idx.features:
                fm_errors.append("%s: affects unknown feature `%s`" % (f.primary, a))
    section("frontmatter fields valid (one_liner <= %d chars, docs exist, affects resolve)" % ONE_LINER_MAX, fm_errors)

    text = idx.text.get("docs/README.md", "")
    if REGISTRY_START in text and REGISTRY_END in text:
        s, e = text.find(REGISTRY_START), text.find(REGISTRY_END)
        current = text[s : e + len(REGISTRY_END)]
        stale = [] if current == render_registry(idx) else ["docs/README.md registry block differs from frontmatter — run `registry`"]
    else:
        stale = ["docs/README.md has no registry markers"]
    section("README registry block is generated from frontmatter", stale)

    section(
        "every service/route module is named by at least one doc",
        orphan_modules(idx),
        fmt=lambda m: m + "   (document it, or allowlist in .cinna-core-kit/docs_index_allowlist.txt)",
    )

    routes = stale_routes(idx)
    if routes is None:
        print("SKIP route citations (frontend/openapi.json not found)")
    else:
        section("route citations exist in frontend/openapi.json", routes, fmt=lambda r: "%s:%d  %s" % r)

    anchoring = []
    for f in idx.features.values():
        for label, p in f.docs:
            if label == "tech" or p.endswith("_tech.md"):
                refs = idx.refs.get(p, set())
                if not any(r.startswith(("backend/", "frontend/")) for r in refs):
                    anchoring.append("%s: tech doc names no backend/ or frontend/ path" % p)
    section("tech docs are anchored to code paths", anchoring)

    unregistered = [
        d for d in idx.docs
        if d not in idx.owner and d != "docs/README.md"
        and not d.startswith(("docs/wiki/", "docs/local_agent_kit/"))
    ]
    section("docs belong to a registered feature", unregistered, failing=False)

    print("\n%s" % ("all checks passed" if failures == 0 else "%d check(s) failed" % failures))
    return 1 if failures else 0


