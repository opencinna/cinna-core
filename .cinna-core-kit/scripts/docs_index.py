def cmd_search(args):
    terms = [a for a in args if not a.startswith("--") and a not in _opt_values(args)]
    if not terms:
        print("usage: search TERM [TERM...] [--limit N] [--feature F] [--domain D] [--include-plans]")
        return 2
    limit = int(_opt(args, "--limit") or 50)
    feature = _opt(args, "--feature")
    domain = _opt(args, "--domain")
    idx = Index(include_plans="--include-plans" in args)
    pats = [re.compile(re.escape(t), re.IGNORECASE) for t in terms]
    hits = 0
    for p in idx.docs:
        owner = idx.owner.get(p)
        if feature and owner != feature:
            continue
        if domain and (owner is None or domain not in idx.features[owner].domains):
            continue
        heading = ""
        file_hits = []
        for n, line in enumerate(idx.text[p].split("\n"), 1):
            if line.startswith("#"):
                heading = line.lstrip("#").strip()
            if all(pt.search(line) for pt in pats):
                file_hits.append((n, heading, line.strip()))
        if not file_hits:
            continue
        print("%s  [%s]" % (p, owner or "-"))
        for n, h, l in file_hits:
            print("  %5d  %s%s" % (n, ("(%s) " % h) if h else "", l[:160]))
            hits += 1
            if hits >= limit:
                print("... limit %d reached; narrow with --feature/--domain or raise --limit" % limit)
                return 0
    if hits == 0:
        print("no hits")
    return 0


