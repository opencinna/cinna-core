# --------------------------------------------------------------------- frontmatter


def _scalar(v):
    v = v.strip()
    if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
        return v[1:-1].replace('\\"', '"')
    return v


def _flow_list(v):
    inner = v.strip()[1:-1].strip()
    if not inner:
        return []
    return [_scalar(x) for x in inner.split(",")]


def parse_frontmatter(text):
    """
    Minimal YAML-subset parser (stdlib only): top-level `key: scalar`,
    `key: [a, b]`, and block mappings / lists nested one level. Returns
    (dict or None, body_text).
    """
    if not text.startswith("---\n"):
        return None, text
    end = text.find("\n---\n", 4)
    if end < 0:
        return None, text
    block = text[4:end]
    body = text[end + 5 :]
    data = {}
    key = None
    for raw in block.split("\n"):
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        if not raw.startswith(" "):
            k, _, v = raw.partition(":")
            key = k.strip()
            v = v.strip()
            if v.startswith("["):
                data[key] = _flow_list(v)
            elif v == "":
                data[key] = None  # filled by nested lines
            else:
                data[key] = _scalar(v)
            continue
        line = raw.strip()
        if key is None:
            continue
        if line.startswith("- "):
            if not isinstance(data.get(key), list):
                data[key] = []
            data[key].append(_scalar(line[2:]))
        else:
            k, _, v = line.partition(":")
            if not isinstance(data.get(key), dict):
                data[key] = {}
            data[key][k.strip()] = _scalar(v)
    return data, body


def strip_frontmatter(text):
    return parse_frontmatter(text)[1]


def dump_frontmatter(fm):
    """Emit the frontmatter block in the canonical key order."""
    lines = ["---"]
    lines.append("feature: %s" % fm["feature"])
    dom = fm["domain"]
    lines.append("domain: %s" % (("[%s]" % ", ".join(dom)) if isinstance(dom, list) else dom))
    lines.append('one_liner: "%s"' % fm["one_liner"].replace('"', '\\"'))
    if fm.get("docs"):
        lines.append("docs:")
        for label, path in fm["docs"].items():
            lines.append("  %s: %s" % (label, path))
    if fm.get("primary_label") and fm["primary_label"] != "business logic":
        lines.append("primary_label: %s" % fm["primary_label"])
    if fm.get("affects"):
        lines.append("affects: [%s]" % ", ".join(fm["affects"]))
    if fm.get("covers"):
        lines.append("covers: [%s]" % ", ".join(fm["covers"]))
    lines.append("---")
    return "\n".join(lines) + "\n"


# -------------------------------------------------------------------- the index


class Feature:
    def __init__(self, name, primary, fm):
        self.name = name
        self.primary = primary  # docs/-rooted path of the doc carrying the frontmatter
        self.fm = fm
        dom = fm.get("domain") or "unknown"
        self.domains = dom if isinstance(dom, list) else [dom]
        self.one_liner = (fm.get("one_liner") or "").strip()
        self.primary_label = fm.get("primary_label") or "business logic"
        self.affects = fm.get("affects") or []
        self.covers = fm.get("covers") or []
        self.docs = []  # [(label, docs/-rooted path)]
        self.docs.append((self.primary_label, primary))
        base = os.path.dirname(primary)
        for label, p in (fm.get("docs") or {}).items():
            if p.startswith("docs/"):
                resolved = p
            else:
                resolved = os.path.normpath(os.path.join(base, p)).replace(os.sep, "/")
            self.docs.append((label, resolved))

    @property
    def doc_paths(self):
        return [p for _, p in self.docs]


class Index:
    def __init__(self, include_plans=False):
        self.docs = indexed_docs(include_plans)
        self.text = {p: read(p) for p in self.docs}
        self.features = {}  # name -> Feature
        self.owner = {}  # doc path -> feature name
        self.errors = []
        for p in self.docs:
            fm, _ = parse_frontmatter(self.text[p])
            if fm is None:
                continue
            name = fm.get("feature")
            if not name:
                self.errors.append("%s: frontmatter without `feature:`" % p)
                continue
            if name in self.features:
                self.errors.append(
                    "%s: duplicate feature `%s` (also in %s)" % (p, name, self.features[name].primary)
                )
                continue
            self.features[name] = Feature(name, p, fm)
        for f in self.features.values():
            for _, d in f.docs:
                if d in self.owner and self.owner[d] != f.name:
                    self.errors.append(
                        "%s claimed by both `%s` and `%s`" % (d, self.owner[d], f.name)
                    )
                self.owner.setdefault(d, f.name)
        self._refs = None
        self._related = None

    # ---- references: doc -> set(root-relative paths it names)
    @property
    def refs(self):
        if self._refs is None:
            self._refs = {}
            for p in self.docs:
                s = set()
                for line in strip_frontmatter(self.text[p]).split("\n"):
                    if "<!-- nocheck -->" in line:
                        continue
                    s.update(CHECKER.extract_references(line, os.path.join(ROOT, p), ROOT))
                self._refs[p] = s
        return self._refs

    # ---- derived related edges (undirected), from doc->doc links
    @property
    def related(self):
        if self._related is None:
            rel_map = defaultdict(set)
            for f in self.features.values():
                for d in f.doc_paths:
                    for r in self.refs.get(d, ()):
                        g = self.owner.get(r)
                        if g and g != f.name:
                            rel_map[f.name].add(g)
                            rel_map[g].add(f.name)
            self._related = rel_map
        return self._related

    def neighbours(self, name):
        out = set(self.related.get(name, ()))
        out.update(self.features[name].affects if name in self.features else ())
        for g in self.features.values():
            if name in g.affects:
                out.add(g.name)
        return out

    def domain_order(self):
        """Domain order is hand-authored in the README's Domain Map table."""
        order = []
        text = self.text.get("docs/README.md", "")
        in_map = False
        for line in text.split("\n"):
            if line.startswith("## Domain Map"):
                in_map = True
                continue
            if in_map and line.startswith("## "):
                break
            if in_map:
                m = re.match(r"\|\s*\[([a-z_]+)\]\(#", line)
                if m:
                    order.append(m.group(1))
        return order


# ---------------------------------------------------------------- registry view


def render_registry(idx):
    order = idx.domain_order()
    by_domain = defaultdict(list)
    for f in idx.features.values():
        for d in f.domains:
            by_domain[d].append(f)
    unknown = [d for d in by_domain if d not in order]
    lines = [REGISTRY_START, GENERATED_NOTE, ""]
    for d in order + sorted(unknown):
        feats = sorted(by_domain.get(d, []), key=lambda f: f.name)
        if not feats:
            continue
        lines.append("### %s" % d)
        lines.append("")
        lines.append("| Feature | Description | Docs | Related |")
        lines.append("|---------|-------------|------|---------|")
        for f in feats:
            docs = " \\| ".join("[%s](%s)" % (label, p[len("docs/"):]) for label, p in f.docs)
            rel_names = [n for n in sorted(idx.related.get(f.name, ())) if n in idx.features]
            aff = [a for a in f.affects if a not in rel_names and a in idx.features]
            shown = rel_names[:RELATED_MAX]
            parts = ["[%s](%s)" % (n, idx.features[n].primary[len("docs/"):]) for n in shown]
            if len(rel_names) > RELATED_MAX:
                parts.append("+%d more" % (len(rel_names) - RELATED_MAX))
            parts += ["[%s](%s) (affects)" % (n, idx.features[n].primary[len("docs/"):]) for n in aff]
            related = ", ".join(parts)
            desc = f.one_liner.replace("|", "\\|")
            lines.append("| %s | %s | %s | %s |" % (f.name, desc, docs, related))
        lines.append("")
    lines.append(REGISTRY_END)
    return "\n".join(lines)


def cmd_registry(args):
    check = "--check" in args
    idx = Index()
    if idx.errors:
        for e in idx.errors:
            print("ERROR:", e)
        return 1
    text = idx.text["docs/README.md"]
    s, e = text.find(REGISTRY_START), text.find(REGISTRY_END)
    if s < 0 or e < 0:
        print("ERROR: docs/README.md has no registry markers; run `seed` first")
        return 1
    new_block = render_registry(idx)
    new_text = text[:s] + new_block + text[e + len(REGISTRY_END):]
    if new_text == text:
        print("Registry block is up to date (%d features)." % len(idx.features))
        return 0
    if check:
        print("STALE: docs/README.md registry block differs from frontmatter; run "
              "`python3 .cinna-core-kit/scripts/docs_index.py registry`")
        return 1
    with open(README, "w", encoding="utf-8") as fh:
        fh.write(new_text)
    print("Regenerated registry block: %d features." % len(idx.features))
    return 0


