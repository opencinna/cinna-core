def _git(argv):
    return subprocess.run(["git", *argv], cwd=ROOT, capture_output=True, text=True).stdout


def _opt(args, flag):
    if flag in args:
        i = args.index(flag)
        if i + 1 < len(args):
            return args[i + 1]
    return None


def _opt_values(args):
    vals = set()
    for flag in ("--limit", "--feature", "--domain", "--base"):
        v = _opt(args, flag)
        if v:
            vals.add(v)
    return vals


def _opt_list(args, flag):
    if flag not in args:
        return []
    out = []
    for a in args[args.index(flag) + 1 :]:
        if a.startswith("--"):
            break
        out.append(a)
    return out


